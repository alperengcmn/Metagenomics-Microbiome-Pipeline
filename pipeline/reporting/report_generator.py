def _df_to_html(df: pd.DataFrame, max_rows: int = 50) -> str:
    """Convert a DataFrame to an HTML table string."""
    if df.empty:
        return "<p><em>No data available.</em></p>"
    display = df.head(max_rows)
    return display.to_html(classes="", border=0, float_format="{:.4f}".format)


def _figure_card(path: Optional[Path], caption: str) -> str:
    """Return HTML for a figure card, or an empty string if path is None."""
    if path is None or not Path(path).exists():
        return ""
    rel = Path(path).name
    return (
        f'<div class="figure-card">'
        f'<img src="figures/{rel}" alt="{caption}">'
        f"<p>{caption}</p>"
        f"</div>"
    )


class ReportGenerator:
    """Compile pipeline results into an HTML report and Markdown summary.

    Args:
        logger: Logger instance.
    """

    def __init__(self, logger: logging.Logger) -> None:
        self.log = logger

    def generate(self, results: Dict[str, Any], output_dir: Path) -> Path:
        """Generate the full HTML analysis report.

        Args:
            results: Dict containing all pipeline module results, config, and figures.
            output_dir: Directory where the report will be written.

        Returns:
            Path to the generated HTML report.
        """
        output_dir.mkdir(parents=True, exist_ok=True)
        sections: List[str] = []

        # 1. Overview
        sections.append(self._section_overview(results))
        # 2. Input
        sections.append(self._section_input(results))
        # 3. QC
        sections.append(self._section_qc(results))
        # 4. Preprocessing
        sections.append(self._section_preprocessing(results))
        # 5. Host filtering
        sections.append(self._section_host_filtering(results))
        # 6. Taxonomy
        sections.append(self._section_taxonomy(results))
        # 7. Diversity
        sections.append(self._section_diversity(results))
        # 8. Statistics
        sections.append(self._section_statistics(results))
        # 9. DA
        sections.append(self._section_differential_abundance(results))
        # 10. Functional
        sections.append(self._section_functional(results))
        # 11. Key findings
        sections.append(self._section_key_findings(results))
        # 12. Parameters
        sections.append(self._section_parameters(results))
        # 13. Reproducibility
        sections.append(self._section_reproducibility(results))

        body = "\n".join(sections)
        date = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        html = _HTML_HEAD + "<h1>Metagenomics Pipeline Report</h1>\n" + body + _HTML_FOOT.format(date=date)

        report_path = output_dir / "pipeline_report.html"
        report_path.write_text(html, encoding="utf-8")
        self.log.info("HTML report written to %s", report_path)

        # Markdown summary
        md_path = self._generate_markdown(results, output_dir, date)
        self.log.info("Markdown summary written to %s", md_path)

        return report_path

    # ------------------------------------------------------------------
    # Section generators
    # ------------------------------------------------------------------

    def _section_overview(self, r: Dict) -> str:
        date = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        n_samples = len(r.get("samples", []))
        config_hash = r.get("config_hash", "n/a")
        return (
            "<h2>1. Analysis Overview</h2>"
            '<div class="summary-grid">'
            f'<div class="stat-card"><div class="value">{n_samples}</div><div class="label">Samples</div></div>'
            f'<div class="stat-card"><div class="value">v1.0.0</div><div class="label">MetaPipe Version</div></div>'
            f'<div class="stat-card"><div class="value">{date[:10]}</div><div class="label">Run Date</div></div>'
            f'<div class="stat-card"><div class="value">{config_hash}</div><div class="label">Config Hash</div></div>'
            "</div>"
        )

    def _section_input(self, r: Dict) -> str:
        samples = r.get("samples", [])
        if not samples:
            return "<h2>2. Input Summary</h2><p>No samples detected.</p>"
        rows = ""
        for s in samples:
            paired = "Paired-end" if getattr(s, "is_paired", False) else "Single-end"
            rows += f"<tr><td>{s.sample_id}</td><td>{paired}</td><td>{s.forward.name}</td></tr>"
        return (
            "<h2>2. Input Summary</h2>"
            "<table><thead><tr><th>Sample ID</th><th>Type</th><th>Forward Read</th></tr></thead>"
            f"<tbody>{rows}</tbody></table>"
        )

    def _section_qc(self, r: Dict) -> str:
        qc = r.get("qc_report", pd.DataFrame())
        figs = r.get("figures", {})
        fig_html = _figure_card(figs.get("qc_summary"), "Read counts before and after QC")
        return (
            "<h2>3. Quality Control Summary</h2>"
            + _df_to_html(qc)
            + '<div class="figure-grid">' + fig_html + "</div>"
        )

    def _section_preprocessing(self, r: Dict) -> str:
        pre = r.get("preprocessing_stats", pd.DataFrame())
        return "<h2>4. Preprocessing Statistics</h2>" + _df_to_html(pre)

    def _section_host_filtering(self, r: Dict) -> str:
        hf = r.get("host_filter_stats", pd.DataFrame())
        return "<h2>5. Host Filtering Summary</h2>" + _df_to_html(hf)

    def _section_taxonomy(self, r: Dict) -> str:
        tax = r.get("taxonomy", {})
        figs = r.get("figures", {})
        matrices = tax.get("abundance_matrices", {})
        out = "<h2>6. Taxonomic Profiling</h2>"
        for level, mat in list(matrices.items())[:2]:
            if not mat.empty:
                out += f"<h3>Top Taxa — {level.capitalize()}</h3>"
                top = mat.mean(axis=1).sort_values(ascending=False).head(10)
                out += _df_to_html(pd.DataFrame({"Mean Relative Abundance": top}))
        out += '<div class="figure-grid">'
        for level in list(matrices.keys())[:2]:
            out += _figure_card(figs.get(f"composition_{level}"), f"Composition — {level}")
            out += _figure_card(figs.get(f"heatmap_{level}"), f"Heatmap — {level}")
        out += "</div>"
        return out

    def _section_diversity(self, r: Dict) -> str:
        div = r.get("diversity", {})
        figs = r.get("figures", {})
        alpha = div.get("alpha_diversity", pd.DataFrame())
        out = "<h2>7. Diversity Analysis</h2><h3>Alpha Diversity</h3>"
        out += _df_to_html(alpha)
        out += '<div class="figure-grid">'
        for metric in ["shannon", "simpson", "observed"]:
            out += _figure_card(figs.get(f"alpha_{metric}"), f"Alpha Diversity — {metric}")
        out += _figure_card(figs.get("pcoa"), "PCoA Ordination")
        out += _figure_card(figs.get("nmds"), "NMDS Ordination")
        out += _figure_card(figs.get("rarefaction"), "Rarefaction Curves")
        out += "</div>"
        return out

    def _section_statistics(self, r: Dict) -> str:
        stat = r.get("statistics", {})
        alpha_tests = stat.get("alpha_diversity_tests", pd.DataFrame())
        permanova = stat.get("permanova_results", {})
        out = "<h2>8. Statistical Findings</h2>"
        out += "<h3>Alpha Diversity Tests</h3>" + _df_to_html(alpha_tests)
        out += "<h3>PERMANOVA Results</h3>"
        if permanova:
            rows = ""
            for metric, res in permanova.items():
                sig = '<span class="badge badge-sig">Significant</span>' if res.get("significant") else "n.s."
                rows += (
                    f"<tr><td>{metric}</td><td>{res.get('F_statistic','n/a')}</td>"
                    f"<td>{res.get('R_squared','n/a')}</td><td>{res.get('p_value','n/a')}</td>"
                    f"<td>{sig}</td></tr>"
                )
            out += (
                "<table><thead><tr><th>Metric</th><th>F</th><th>R²</th><th>p-value</th><th>Result</th></tr></thead>"
                f"<tbody>{rows}</tbody></table>"
            )
        else:
            out += "<p>PERMANOVA was not performed.</p>"
        return out

    def _section_differential_abundance(self, r: Dict) -> str:
        stat = r.get("statistics", {})
        da = stat.get("differential_abundance", pd.DataFrame())
        figs = r.get("figures", {})
        out = "<h2>9. Differential Abundance</h2>"
        if not isinstance(da, pd.DataFrame) or da.empty:
            out += "<p>No differential abundance results.</p>"
        else:
            sig = da[da.get("significant", pd.Series(False, index=da.index))]
            out += f"<p>{len(sig)} taxa significantly differentially abundant.</p>"
            out += _df_to_html(da.head(20))
        out += '<div class="figure-grid">' + _figure_card(figs.get("volcano"), "Volcano Plot") + "</div>"
        return out

    def _section_functional(self, r: Dict) -> str:
        func = r.get("functional", {})
        figs = r.get("figures", {})
        pathways = func.get("pathways", pd.DataFrame())
        out = "<h2>10. Functional Profiling</h2>"
        if isinstance(pathways, pd.DataFrame) and not pathways.empty:
            out += f"<p>{len(pathways)} pathways detected.</p>"
            out += _df_to_html(pathways.head(15))
        else:
            out += "<p>Functional profiling was not performed or returned no results.</p>"
        out += '<div class="figure-grid">' + _figure_card(figs.get("functional_heatmap"), "Functional Heatmap") + "</div>"
        return out

    def _section_key_findings(self, r: Dict) -> str:
        interp = r.get("interpretation")
        out = "<h2>11. Key Biological Findings</h2>"
        if interp is None:
            return out + "<p>No biological interpretation available.</p>"
        findings = getattr(interp, "all_findings", [])
        if not findings:
            return out + "<p>No findings to report.</p>"
        out += "<ul>" + "".join(f"<li>{f}</li>" for f in findings) + "</ul>"
        return out

    def _section_parameters(self, r: Dict) -> str:
        config = r.get("config")
        out = "<h2>12. Analysis Parameters</h2>"
        if config is not None:
            try:
                cfg_dict = config.model_dump()
                out += f"<pre>{json.dumps(cfg_dict, indent=2, default=str)}</pre>"
            except Exception:
                out += "<p>Configuration unavailable.</p>"
        return out

    def _section_reproducibility(self, r: Dict) -> str:
        config_hash = r.get("config_hash", "n/a")
        cmd = r.get("command", "metapipe run --input <input> --output <output>")
        return (
            "<h2>13. Reproducibility</h2>"
            f"<p><strong>Configuration hash:</strong> <code>{config_hash}</code></p>"
            f"<p><strong>Command used:</strong></p>"
            f"<pre>{cmd}</pre>"
            "<p>To reproduce this analysis, use the same config file and input data. "
            "The configuration hash can be used to verify parameter consistency.</p>"
        )

    def _generate_markdown(self, r: Dict, output_dir: Path, date: str) -> Path:
        """Write a concise Markdown summary of the analysis."""
        lines = [
            "# Metagenomics Pipeline — Analysis Summary",
            f"\n**Date:** {date}  ",
            f"**Samples:** {len(r.get('samples', []))}  ",
            f"**Config hash:** {r.get('config_hash', 'n/a')}  ",
            "\n---\n",
            "## Key Findings\n",
        ]
        interp = r.get("interpretation")
        if interp:
            for finding in getattr(interp, "all_findings", []):
                lines.append(f"- {finding}")

        lines += [
            "\n---\n",
            "## Output Files\n",
            "| File | Description |",
            "|------|-------------|",
            "| `pipeline_report.html` | Full interactive HTML report |",
            "| `pipeline.log` | Detailed run log |",
            "| `figures/` | All generated figures |",
            "| `taxonomy/` | Abundance tables per taxonomic level |",
        ]

        md_path = output_dir / "summary.md"
        md_path.write_text("\n".join(lines), encoding="utf-8")
        return md_path
